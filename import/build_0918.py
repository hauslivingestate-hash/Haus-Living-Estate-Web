report = io.open(os.path.join(HERE, "build_0918_report.txt"), "w", encoding="utf-8")
def rp(*a):
    line = " ".join(str(x) for x in a)
    sys.stdout.buffer.write((line + "\n").encode("utf-8"))
    report.write(line + "\n")

def load(name):
    with io.open(os.path.join(HERE, "18-09" + name), encoding="utf-8-sig", newline="") as fh:
        return list(csv.reader(fh))

def s(v):
    v = (v or "").strip()
    return v or None

def date(v):
    m = re.fullmatch(r"(\d{1,2})/(\d{1,2})/(\d{4})", (v or "").strip())
    if not m: return None
    d, mo, y = map(int, m.groups())
    if y > 2400: y -= 543
    if y < 2000 or not (1 <= mo <= 12 and 1 <= d <= 31): return None   # 30/12/1899 = empty cell
    return "%04d-%02d-%02d" % (y, mo, d)

def num(v):
    # the 08-03 import lost every Last Match price because "฿3,600,000" failed this parse
    v = (v or "").replace(",", "").replace("฿", "").strip()
    if not v or v == "-": return None
    return float(v) if re.fullmatch(r"-?\d+(\.\d+)?", v) else None

def integer(v):
    n = num(v)
    return int(n) if n is not None else None

def boolean(v):
    v = (v or "").strip().upper()
    return True if v == "TRUE" else (False if v == "FALSE" else None)

def link(v):
    v = (v or "").strip()
    return None if not v or v.upper() in ("TRUE", "FALSE") else v

def lit(v):
    if v is None: return "NULL"
    if isinstance(v, bool): return "TRUE" if v else "FALSE"
    if isinstance(v, (int, float)): return repr(v)
    return "'" + str(v).replace("'", "''") + "'"

def only(v, table):
    return v if v in set(LK[table]) else None

NICK = {h["nick"]: h["code"] for h in LK["hr"]}
NICK.update({"Stone Bangyai": "C-001", "Stone+Pup": "C-001"})
def emp(v):
    return NICK.get((v or "").strip())

ZONE = {}
for z in LK["zone"]:
    for k in (z["name_eng"], z["name_thai"]):
        if k and k != "Out of zone" and k != "นอกโซน":
            ZONE[k.strip()] = z["zone_id"]
ZONE.update({"Don Mueang": "DMK", "Ngamwongwan": "NGM", "Ratchaphruek (ต้น)": "RP1"})
