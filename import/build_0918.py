def insert(table, rows):
    cols = list(rows[0].keys())
    vals = ",\n".join("  (%s)" % ", ".join(r[c] if isinstance(r[c], Raw) else lit(r[c]) for c in cols) for r in rows)
    return "insert into %s (%s) values\n%s;\n" % (table, ", ".join(cols), vals)

class Raw(str):
    """A value written into the SQL verbatim (a subselect)."""

